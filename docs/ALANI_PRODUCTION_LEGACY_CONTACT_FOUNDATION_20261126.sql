  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete restrict,
  source_serial integer not null check (source_serial between 1 and 10000000),
  source_row integer not null check (source_row between 2 and 10000002),
  recipient_name text not null check (char_length(trim(recipient_name)) between 1 and 160),
  phone_primary text not null check (phone_primary ~ '^07[3-9][0-9]{8}$'),
  phone_secondary text check (phone_secondary is null or phone_secondary ~ '^07[3-9][0-9]{8}$'),
  historical_order_count integer not null default 0 check (historical_order_count>=0),
  governorate text not null default '' check(char_length(governorate)<150),
  district text not null default '' check(char_length(district)<200),
  address_details text not null default '' check(char_length(address_details)<1500),
  goods_type text not null default '' check(char_length(goods_type)<1000),
  linked_user_id uuid references auth.users(id) on delete set null,
  source_batch_id uuid not null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, phone_primary)
