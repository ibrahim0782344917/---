-- REVIEW ONLY: Not applied to production. No customer data is stored here.
-- Requires isolated Staging DB, backup+restore test, and approval first.
-- Historical customers are private contacts, NOT Supabase Auth users.
begin;

create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;

create table if not exists app_private.alani_legacy_customers (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores(id) on delete restrict,
  source_serial integer not null check (source_serial between 1 and 10000000),
  source_row integer not null check (source_row between 2 and 10000002),
  recipient_name text not null check (char_length(trim(recipient_name)) between 1 and 160),
  phone_primary text not null check (phone_primary ~ '^07[3-9][0-9]{8}$'),
  phone_secondary text check (phone_secondary is null or phone_secondary ~ '^07[3-9][0-9]{8}$'),
  historical_order_count integer not null default 0 check (historical_order_count>=0),
  governorate text not null default '' check(char_length(governorate)<150),
  district text not null default '' check(char_length(district)<200),
  address_details text not null default '' check(char_length(address_details)<1500),
  goods_type text not null default '' check(char_length(goods_type)<1000),
  linked_user_id uuid references auth.users(id) on delete set null,
  source_batch_id uuid not null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (store_id, phone_primary)
);

create index if not exists idx_alani_legacy_contacts_store
  on app_private.alani_legacy_customers(store_id,created_at desc);

alter table app_private.alani_legacy_customers enable row level security;
revoke all on app_private.alani_legacy_customers from PUBLIC,anon,authenticated;

-- No direct RLS policies, grants or public RPCs for clients.
-- Ingestion must occur through a private authenticated server endpoint which
-- verifies that auth subject == store owner, enforces MFA as configured,
-- imports in 50-200-row transactions, tests idempotency / duplicate collision,
-- writes immutable audit, and never logs full phone/address payloads.
-- No autogenerated login, password, invite, SMS, or financial order.
-- Only a verified, consent-aware linkage can set linked_user_id.

commit;
